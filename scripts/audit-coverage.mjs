// ─────────────────────────────────────────────────────────────────
// SKO-476 sensitive write-route audit coverage inventory.
//
//   node scripts/audit-coverage.mjs           # print summary, write docs
//   node scripts/audit-coverage.mjs --check   # fail if an uncovered sensitive
//                                             # route is not a reviewed exclusion
//
// A mutating route (POST/PUT/PATCH/DELETE) counts as covered when the route
// file, or a module it imports (up to three `@/` hops), writes an AuditLog
// row. This is static evidence of an audit write path, not proof that every
// branch emits one; database tests cover the behaviour of key routes.
// ─────────────────────────────────────────────────────────────────
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SENSITIVE = /\/api\/(students|pupils|marks|exams|fees|payments|invoices|corrections|staff|roles|memberships|guardians|parent-invitations|reports|users|import-batches|school-ai\/exams|accounts|payroll|admissions|data-lifecycle|owner\/support|subscriptions|billing)(\/|$)/;
const AUDIT_WRITE = /auditLog\.(create|createMany)\b/;
const EXCLUSIONS_FILE = path.join(root, "docs/operations/audit-coverage-exclusions.json");

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name === "route.ts") out.push(full);
  }
  return out;
}
function resolveImport(spec) {
  if (!spec.startsWith("@/")) return null;
  const base = path.join(root, "src", spec.slice(2));
  for (const candidate of [base, `${base}.ts`, `${base}.tsx`, path.join(base, "index.ts")]) if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  return null;
}
const cache = new Map();
function writesAudit(file, depth = 0, seen = new Set()) {
  if (seen.has(file)) return false;
  seen.add(file);
  const key = `${file}:${depth}`;
  if (cache.has(key)) return cache.get(key);
  const source = fs.readFileSync(file, "utf8");
  let result = AUDIT_WRITE.test(source);
  if (!result && depth < 3) {
    for (const match of source.matchAll(/from\s+["'](@\/[^"']+)["']/g)) {
      const target = resolveImport(match[1]);
      if (target && writesAudit(target, depth + 1, seen)) { result = true; break; }
    }
  }
  cache.set(key, result);
  return result;
}

const routes = walk(path.join(root, "src/app/api")).sort().map(file => {
  const source = fs.readFileSync(file, "utf8");
  const methods = [...source.matchAll(/export\s+(?:async\s+)?(?:function|const)\s+(POST|PUT|PATCH|DELETE)\b/g)].map(match => match[1]);
  const route = "/" + path.relative(path.join(root, "src/app"), path.dirname(file)).split(path.sep).join("/");
  return { route, methods: [...new Set(methods)], sensitive: SENSITIVE.test(route), covered: methods.length ? writesAudit(file) : null };
}).filter(item => item.methods.length);

const exclusions = fs.existsSync(EXCLUSIONS_FILE) ? JSON.parse(fs.readFileSync(EXCLUSIONS_FILE, "utf8")) : {};
const sensitive = routes.filter(item => item.sensitive);
const uncovered = sensitive.filter(item => !item.covered);
const unreviewed = uncovered.filter(item => !exclusions[item.route]);
const stale = Object.keys(exclusions).filter(route => !uncovered.some(item => item.route === route));

if (process.argv.includes("--check")) {
  if (unreviewed.length || stale.length) {
    for (const item of unreviewed) console.error(`Uncovered sensitive write route without a reviewed exclusion: ${item.route} [${item.methods.join(", ")}]`);
    for (const route of stale) console.error(`Exclusion no longer needed (route covered or removed): ${route}`);
    process.exitCode = 1;
  } else console.log(`Audit coverage: ${sensitive.length - uncovered.length}/${sensitive.length} sensitive write routes write audit events; ${uncovered.length} reviewed exclusions.`);
} else {
  const lines = [
    "# Sensitive write-route audit coverage (SKO-476)",
    "",
    "Generated by `node scripts/audit-coverage.mjs`. A route counts as covered when it, or a module it imports (up to three `@/` hops), writes an `AuditLog` row. This is static evidence of an audit write path; database tests prove the behaviour of key flows. `npm run check:audit-coverage` fails when a new sensitive write route has neither coverage nor a reviewed exclusion.",
    "",
    `- Mutating API routes: **${routes.length}**`,
    `- Sensitive-domain mutating routes: **${sensitive.length}**`,
    `- Covered by an audit write path: **${sensitive.length - uncovered.length}**`,
    `- Reviewed exclusions: **${uncovered.length}** (see \`audit-coverage-exclusions.json\` for the reason per route)`,
    "",
    "| Route | Methods | Audit write path | Exclusion reason |",
    "| --- | --- | --- | --- |",
    ...sensitive.map(item => `| \`${item.route}\` | ${item.methods.join(", ")} | ${item.covered ? "yes" : "no"} | ${item.covered ? "" : (exclusions[item.route] ?? "**unreviewed**")} |`),
    "",
  ];
  fs.writeFileSync(path.join(root, "docs/operations/audit-coverage.md"), lines.join("\n"));
  console.log(JSON.stringify({ mutating: routes.length, sensitive: sensitive.length, covered: sensitive.length - uncovered.length, uncovered: uncovered.map(item => `${item.route} [${item.methods.join(",")}]`) }, null, 1));
}
