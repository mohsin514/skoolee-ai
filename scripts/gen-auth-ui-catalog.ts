/**
 * SKAI-1004: generates the Arabic and Urdu UI-catalog subsets for the pre-login (auth) pages.
 *
 * The full catalog (`src/lib/locale/ui-messages`) is ~600 KB gzip per cold Arabic /login. The (auth)
 * pages translate their own copy, so `translateUi` there only ever sees the string literals in their
 * client import graph. This walks that graph from every (auth) page and layout, keeps each literal
 * the full catalog translates, and writes one small module per language.
 *
 *   npx tsx scripts/gen-auth-ui-catalog.ts          # write
 *   npx tsx scripts/gen-auth-ui-catalog.ts --check  # exit 1 if the committed files are stale
 *
 * tests/perf/auth-ui-catalog.test.ts runs the check, so a new auth string cannot ship untranslated.
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { translateUi } from "../src/lib/locale/ui-messages";

const ROOT = resolve(__dirname, "..");
const AUTH_DIR = join(ROOT, "src/app/(auth)");
const EXTENSIONS = [".tsx", ".ts", ".jsx", ".js"];
const OUT = (lang: string) => join(ROOT, `src/lib/locale/auth-ui-catalog.${lang}.ts`);

function entryFiles(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...entryFiles(path));
    else if (/^(page|layout|loading|error|not-found)\.(tsx|ts)$/.test(name)) out.push(path);
  }
  return out;
}

function resolveImport(from: string, spec: string): string | undefined {
  let base: string;
  if (spec.startsWith("@/")) base = join(ROOT, "src", spec.slice(2));
  else if (spec.startsWith(".")) base = resolve(dirname(from), spec);
  else return undefined; // packages are not part of our copy
  for (const candidate of [base, ...EXTENSIONS.map((e) => base + e), ...EXTENSIONS.map((e) => join(base, "index" + e))]) {
    if (existsSync(candidate) && statSync(candidate).isFile()) return candidate;
  }
  return undefined;
}

/** Static and dynamic imports, minus type-only ones. */
function importsOf(src: string): string[] {
  const specs: string[] = [];
  for (const m of src.matchAll(/^\s*(?:import|export)(?!\s+type\b)[^;'"]*?from\s+["']([^"']+)["']/gm)) specs.push(m[1]);
  for (const m of src.matchAll(/^\s*import\s+["']([^"']+)["']/gm)) specs.push(m[1]);
  for (const m of src.matchAll(/import\(\s*["']([^"']+)["']\s*\)/g)) specs.push(m[1]);
  return specs;
}

/** Server-only modules and server actions never reach the browser bundle. */
function shipsToClient(src: string): boolean {
  return !/^\s*["']use server["']/m.test(src) && !/^\s*import\s+["']server-only["']/m.test(src);
}

export function collectLiterals(): Set<string> {
  const seen = new Set<string>();
  const literals = new Set<string>();
  const queue = entryFiles(AUTH_DIR);
  while (queue.length) {
    const file = queue.pop()!;
    if (seen.has(file)) continue;
    seen.add(file);
    // The catalogs themselves hold every string in the app; they are what we are subsetting.
    if (/src\/lib\/locale\/([a-z-]*ui-messages|role-ux\/|auth-ui-catalog)/.test(file)) continue;
    const src = readFileSync(file, "utf8");
    if (!shipsToClient(src)) continue;
    for (const m of src.matchAll(/"((?:[^"\\\n]|\\.)*)"/g)) { try { literals.add(JSON.parse(`"${m[1]}"`)); } catch { /* not a plain string */ } }
    for (const m of src.matchAll(/'((?:[^'\\\n]|\\.)*)'/g)) { try { literals.add(JSON.parse(`"${m[1].replace(/\\'/g, "'").replace(/"/g, '\\"')}"`)); } catch { /* not a plain string */ } }
    for (const m of src.matchAll(/`((?:[^`\\$]|\\.|\$(?!\{))*)`/g)) literals.add(m[1]);
    for (const spec of importsOf(src)) {
      const next = resolveImport(file, spec);
      if (next) queue.push(next);
    }
  }
  return literals;
}

export function buildCatalog(language: "ar" | "ur"): Record<string, string> {
  const entries: [string, string][] = [];
  // Most literals are class names or keys, not copy; the catalog's dev-mode "missing" warning would flood the log.
  const warn = console.warn;
  console.warn = () => {};
  try {
    for (const source of collectLiterals()) {
      if (!/[a-zA-Z]{2}/.test(source)) continue;
      const value = translateUi(source, language);
      if (value !== source) entries.push([source, value]);
    }
  } finally { console.warn = warn; }
  entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return Object.fromEntries(entries);
}

export function renderModule(language: "ar" | "ur"): string {
  const body = JSON.stringify(buildCatalog(language), null, 1).replace(/\n /g, "\n  ");
  return `// GENERATED by scripts/gen-auth-ui-catalog.ts (SKAI-1004). Do not edit; run \`npm run gen:auth-ui-catalog\`.
// ${language === "ar" ? "Arabic" : "Urdu"} UI-catalog entries reachable from the pre-login (auth) pages.
const catalog: Record<string, string> = ${body};
export default catalog;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(__filename)) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const lang of ["ar", "ur"] as const) {
    const next = renderModule(lang);
    const path = OUT(lang);
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current === next) continue;
    if (check) { stale = true; console.error(`${relative(ROOT, path)} is stale. Run: npm run gen:auth-ui-catalog`); }
    else { writeFileSync(path, next); console.log(`wrote ${relative(ROOT, path)} (${Object.keys(buildCatalog(lang)).length} entries)`); }
  }
  if (stale) process.exit(1);
}
