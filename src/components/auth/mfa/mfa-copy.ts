/** Reason → localised guidance; the server's English `error` is only a last resort. */
export function mfaErrorText(t: Pick<MfaCopy, "reasons" | "recoveryRace" | "unavailable">, error: { reason?: string; message?: string }, recovery: boolean) {
  if (error.reason === "code_reused" && recovery) return t.recoveryRace;
  if (error.reason && error.reason in t.reasons) return t.reasons[error.reason as MfaReason];
  return error.message || t.unavailable;
}
