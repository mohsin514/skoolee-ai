import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => {
  const interactive = typeof props.onClick === "function";
  return (
    <div
      ref={ref}
      className={cn(
        "rounded-[28px] border border-[#cfc2d6]/25 bg-white text-[#1f1a23] shadow-[0_4px_16px_-4px_rgba(31,26,35,0.10),0_12px_32px_-12px_rgba(129,39,207,0.20)] transition-all duration-200",
        interactive
          ? "cursor-pointer hover:-translate-y-1 hover:border-[#8127cf]/25 hover:shadow-[0_10px_28px_-6px_rgba(31,26,35,0.14),0_22px_50px_-16px_rgba(129,39,207,0.32)]"
          : "hover:border-[#8127cf]/20",
        className
      )}
      {...props}
    />
  );
});
Card.displayName = "Card";

