export function onboardingCopy(language: string | null | undefined): OnboardingCopy {
  const code = (language || "en").slice(0, 2).toLowerCase();
  return code === "ar" ? ar : code === "ur" ? ur : en;
}

export function isRtlLanguage(language: string | null | undefined) {
  const code = (language || "en").slice(0, 2).toLowerCase();
  return code === "ar" || code === "ur";
}

/** "{0} of {1}" style interpolation. */
export function fill(template: string, ...values: (string | number)[]) {
  return template.replace(/\{(\d+)\}/g, (match, index) => (index in values ? String(values[Number(index)]) : match));
}
