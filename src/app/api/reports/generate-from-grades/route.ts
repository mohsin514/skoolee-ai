import { NextRequest, NextResponse } from "next/server";
import { prisma, type TxClient } from "@/lib/db/prisma";
import { writeAuditEvent } from "@/lib/audit-events";
import { getAuthUser } from "@/lib/auth";
import { calculateWeightedGradeForClass } from "@/lib/academic/grade-calculator";
import { ReportConflict, refreshVersion, versionTransaction } from "@/lib/academic/report-versions";
import { findOrCreateFinalExam, lockFinalGradeScope } from "@/lib/academic/final-grade-exam";
import { canLeadAcademics, canManageAcademics } from "@/lib/api/scope";
import { parseBody } from "@/lib/api/validate";
import { jsonObjectBody } from "@/lib/validators/route-bodies";

/** A teacher previews weighted grades only for a class they teach (class teacher or a subject teacher). */
async function teachesClass(userId: string, campusId: string, classId: string) {
  return Boolean(await prisma.class.findFirst({ where: { id: classId, campusId, OR: [{ classTeacherId: userId }, { subjects: { some: { teacherId: userId } } }] }, select: { id: true } }));
}

export async function GET(req: NextRequest) {
  try {
    const user = await getAuthUser();
    if (!user || !user.campusId) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }
    // G33: the weighted preview is for the academic office and for teachers of the class.
    if (user.role !== "TEACHER" && !canManageAcademics(user)) {
      return NextResponse.json({ error: "Insufficient permissions" }, { status: 403 });
    }

    const { searchParams } = new URL(req.url);
    const studentId = searchParams.get("studentId");
    const classId = searchParams.get("classId");
    const academicYear = Number(searchParams.get("academicYear")) || new Date().getFullYear();

    if (!studentId || !classId) {
      return NextResponse.json({ error: "studentId and classId are required" }, { status: 400 });
    }
    if (user.role === "TEACHER" && !(await teachesClass(user.userId, user.campusId, classId))) {
      return NextResponse.json({ error: "You can preview grades only for classes you teach." }, { status: 403 });
    }

    const finalExam = await prisma.exam.findFirst({
      where: { campusId: user.campusId, classId, academicYear, examType: "FINAL", subjectId: null },
    });

    if (!finalExam) {
      return NextResponse.json({ reportCard: null });
    }

    const reportCard = await prisma.reportCard.findFirst({
      where: { examId: finalExam.id, studentId },
      include: {
        exam: { select: { id: true, title: true, term: true } },
        student: {
          select: { id: true, fullName: true, rollNo: true, profileImageUrl: true, class: { select: { id: true, name: true, section: true } } },
        },
      },
    });

    // Attach subject breakdown from grade calculator
    let subjectBreakdown: any[] = [];
    if (reportCard) {
      try {
        const { calculateWeightedGrade } = await import("@/lib/academic/grade-calculator");
        const gradeDetail = await calculateWeightedGrade(studentId, user.campusId, classId, academicYear);
        subjectBreakdown = gradeDetail.subjectBreakdown || [];
      } catch {}
    }

    // SKAI-1338: no final report card means null, not an empty card with a fabricated breakdown.
    return NextResponse.json({ reportCard: reportCard ? { ...reportCard, subjectBreakdown } : null });
  } catch (error: any) {
    console.error("Generate-from-grades GET error:", error);
    return NextResponse.json({ error: error?.message || "Internal server error" }, { status: 500 });
  }
}

export async function POST(req: NextRequest) {
  try {
    const user = await getAuthUser();
    if (!user || !user.campusId) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }
    // G33 (M61): generating final grades creates a PUBLISHED final exam and report cards, so it is the
    // academic lead's act — the principal, or a campus operator while the campus has no principal.
    // Teachers keep the weighted preview (GET) only.
    if (!(await canLeadAcademics(user, user.campusId))) {
      return NextResponse.json({ error: "Final grades are generated by your principal." }, { status: 403 });
    }

    const { classId, academicYear } = await parseBody(req, jsonObjectBody);
    if (!classId || !academicYear) {
      return NextResponse.json({ error: "classId and academicYear are required" }, { status: 400 });
    }
    // SKAI-1340: a malformed year is a client error with a plain message, never a 500 that exposes ORM internals.
    const year = Number(academicYear);
    if (!Number.isInteger(year) || year < 2000 || year > 2100) {
      return NextResponse.json({ error: "academicYear must be a four-digit year" }, { status: 400 });
    }

    const cls = await prisma.class.findFirst({
      where: { id: classId, campusId: user.campusId },
      select: { id: true, name: true, section: true },
    });
    if (!cls) return NextResponse.json({ error: "Class not found" }, { status: 404 });

    // SKAI-1688: find or create the synthetic "Final Grade" exam under a per-scope lock, so a race makes one exam.
    const { exam: finalExam } = await prisma.$transaction((tx) => findOrCreateFinalExam(tx as TxClient, user, user.campusId!, cls, year));

    // Calculate weighted grades for all students
    const grades = await calculateWeightedGradeForClass(classId, user.campusId, Number(academicYear));
    if (!grades.length) {
      return NextResponse.json({ error: "No grade data available. Ensure exams have marks entered." }, { status: 400 });
    }

    const subjects = await prisma.subject.findMany({
      where: { classId, campusId: user.campusId },
      select: { id: true, name: true, totalMarks: true },
    });

    const studentIds = grades.map((g) => g.studentId);
    const existingCards = await prisma.reportCard.findMany({
      where: { examId: finalExam.id, studentId: { in: studentIds } },
      select: { id: true, studentId: true },
    });
    const existingMap = new Map(existingCards.map((c) => [c.studentId, c.id]));
    const totalMarks = subjects.reduce((s, sub) => s + sub.totalMarks, 0);
    const now = new Date();

    const examId = finalExam.id;
    const writes = grades.map((grade) => {
      const marks = {
        totalMarks,
        obtainedMarks: grade.subjectBreakdown.reduce((s, sb) => s + sb.obtainedMarks, 0),
        percentage: grade.overallPercentage,
        grade: grade.overallGrade,
        rank: (grade as any).rank || 0,
        generatedAt: now,
      };
      return { marks, studentId: grade.studentId, existingId: existingMap.get(grade.studentId) };
    });

    // Existing cards keep their remarks, delivery history and published version. Changed marks go through the
    // report-version workflow, which records a new reviewable version and clears approval and the PDF.
    await versionTransaction(async (tx) => {
      // SKAI-1688: the same lock serialises card writes; a stale loser aborts as a ReportConflict (409), never a duplicate.
      await lockFinalGradeScope(tx, user.campusId!, classId, year);
      for (const { marks, studentId, existingId } of writes) {
        const card = existingId
          ? await tx.reportCard.update({ where: { id: existingId }, data: marks })
          : await tx.reportCard.create({ data: { ...marks, status: "PUBLISHED", remarksEn: null, remarksUr: null, remarksApproved: false, isSent: false, deliveryStatus: "PENDING", campusId: user.campusId!, examId, studentId } });
        if (existingId) await refreshVersion(tx, card.id);
        await writeAuditEvent(tx, user, {
          table: "report_cards", recordId: card.id, action: existingId ? "UPDATE" : "CREATE", campusId: card.campusId,
          after: { examId, studentId, status: card.status, totalMarks: card.totalMarks, obtainedMarks: card.obtainedMarks, percentage: card.percentage, grade: card.grade, rank: card.rank },
        });
      }
    });

    return NextResponse.json({ success: true, count: grades.length });
  } catch (error: any) {
    if (error instanceof ReportConflict) {
      return NextResponse.json({ error: "Final grades are already being generated for this class. Reload to see the result." }, { status: 409 });
    }
    console.error("Generate-from-grades error:", error);
    // SKAI-1340: the detail stays in the server log; the client gets a plain message.
    return NextResponse.json({ error: "Something went wrong. Please try again." }, { status: 500 });
  }
}
